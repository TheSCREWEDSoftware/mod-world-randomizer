#!/usr/bin/env python3
"""Writes web/conf-templates.js: the current .conf.dist of this module (and of mod-dynamic-scaling, when it sits next
to it in modules/), for the web page that updates an old config file (web/config.html).

Run it after changing a .conf.dist:  python3 tools/make_conf_templates.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
MODULE = os.path.dirname(HERE)
MODULES = os.path.dirname(MODULE)

SOURCES = [
    ("mod-world-randomizer", "World Randomizer", "Randomizer."),
    ("mod-dynamic-scaling", "Dynamic Scaling", "DynamicScaling."),
]

templates = {}
for name, title, prefix in SOURCES:
    path = os.path.join(MODULES, name, "conf", name + ".conf.dist")
    if not os.path.exists(path):
        print("skipped (not found):", path)
        continue
    with open(path, encoding="utf-8") as f:
        text = f.read().replace("\r\n", "\n")
    templates[name] = {"title": title, "file": name + ".conf", "prefix": prefix, "text": text}
    print("added", path)

out = os.path.join(MODULE, "web", "conf-templates.js")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by tools/make_conf_templates.py from the modules' .conf.dist files. Do not edit by hand.\n")
    f.write("window.MODULE_CONF_TEMPLATES = ")
    json.dump(templates, f, indent=1, ensure_ascii=False)
    f.write(";\n")
print("wrote", out)
